begin;

-- ============================================================================
-- 보안 보완
--   1. 초기 비밀번호 강제 변경 우회 차단
--   2. 일회용 연결 코드에 72시간 유효기간 부여
--   3. 내부 DB 오류 메시지(sqlerrm) 노출 차단
--   4. 권한·명단 변경 감사 로그
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1 & 2. 컬럼 추가
-- ----------------------------------------------------------------------------
-- password_baseline: 강제 변경 대상자를 처음 본 시점의 auth 비밀번호 해시.
--   completePasswordChange 는 현재 해시가 이 값과 달라졌을 때만 플래그를 내린다.
-- code_expires_at: 일회용 연결 코드의 만료 시각. internal- 코드에는 두지 않는다.
alter table public.app_users
  add column if not exists password_baseline text,
  add column if not exists code_expires_at timestamptz;


-- ----------------------------------------------------------------------------
-- 2. 코드가 발급·재발급될 때마다 만료 시각을 자동으로 갱신한다.
--    setLeader / regenerateCode / createAdminInvitation / regenerateAdminCode 등
--    코드를 만드는 모든 경로를 트리거 한 곳에서 덮는다.
-- ----------------------------------------------------------------------------
create or replace function public.app_users_touch_code_expiry()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' or new.access_code is distinct from old.access_code then
    new.code_expires_at := case
      when new.access_code like 'internal-%' then null
      else now() + interval '72 hours'
    end;
  end if;
  return new;
end;
$$;

drop trigger if exists app_users_code_expiry on public.app_users;
create trigger app_users_code_expiry
before insert or update of access_code on public.app_users
for each row execute function public.app_users_touch_code_expiry();

-- 이미 발급돼 있던 미사용 코드에는 지금부터 72시간의 유예를 준다.
-- (이 UPDATE 는 access_code 를 건드리지 않으므로 트리거가 값을 덮어쓰지 않는다.)
update public.app_users
set code_expires_at = now() + interval '72 hours'
where auth_user_id is null
  and active
  and code_expires_at is null;

-- 강제 변경 대상자의 현재 비밀번호 해시를 기준값으로 고정한다.
update public.app_users u
set password_baseline = a.encrypted_password
from auth.users a
where a.id = u.auth_user_id
  and u.must_change_password
  and u.password_baseline is null;


-- ----------------------------------------------------------------------------
-- 4. 감사 로그
-- ----------------------------------------------------------------------------
create table if not exists public.admin_audit (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  actor_user_id text,
  actor_auth_id uuid,
  actor_name text not null default '',
  action text not null,
  ok boolean not null,
  detail jsonb not null default '{}'::jsonb
);

create index if not exists admin_audit_occurred_idx on public.admin_audit(occurred_at desc);
create index if not exists admin_audit_actor_idx on public.admin_audit(actor_user_id, occurred_at desc);

alter table public.admin_audit enable row level security;
revoke all on public.admin_audit from anon, authenticated;

-- 감사 로그는 이름·전화번호 같은 본문이 아니라 식별자와 건수만 남긴다.
create or replace function public.attendance_audit(
  p_actor_user_id text,
  p_actor_auth_id uuid,
  p_actor_name text,
  p_action text,
  p_ok boolean,
  p_detail jsonb
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.admin_audit(actor_user_id, actor_auth_id, actor_name, action, ok, detail)
  values (
    p_actor_user_id,
    p_actor_auth_id,
    coalesce(p_actor_name, ''),
    p_action,
    p_ok,
    coalesce(p_detail, '{}'::jsonb)
  );
end;
$$;


-- ----------------------------------------------------------------------------
-- 2. 연결 코드 만료를 검사하도록 claim 갱신
-- ----------------------------------------------------------------------------
create or replace function public.attendance_claim_account(p_code text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_auth_user_id uuid := auth.uid();
  v_user public.app_users%rowtype;
  v_attempt public.auth_claim_attempts%rowtype;
  v_email_confirmed_at timestamptz;
begin
  if v_auth_user_id is null then
    return jsonb_build_object('ok', false, 'error', '로그인이 필요합니다.');
  end if;

  select email_confirmed_at into v_email_confirmed_at
  from auth.users
  where id = v_auth_user_id;
  if v_email_confirmed_at is null then
    return jsonb_build_object('ok', false, 'error', '이메일 인증을 먼저 완료하세요.');
  end if;

  select * into v_user
  from public.app_users
  where auth_user_id = v_auth_user_id
    and active
    and (access_expires_on is null or access_expires_on >= current_date)
  limit 1;
  if v_user.id is not null then
    return jsonb_build_object('ok', true, 'alreadyLinked', true);
  end if;

  insert into public.auth_claim_attempts(auth_user_id)
  values (v_auth_user_id)
  on conflict (auth_user_id) do nothing;

  select * into v_attempt
  from public.auth_claim_attempts
  where auth_user_id = v_auth_user_id
  for update;

  if v_attempt.window_started_at < now() - interval '1 hour' then
    update public.auth_claim_attempts
    set window_started_at = now(), failed_attempts = 0
    where auth_user_id = v_auth_user_id;
    v_attempt.failed_attempts := 0;
  end if;

  if v_attempt.failed_attempts >= 5 then
    return jsonb_build_object('ok', false, 'error', '연결 시도 횟수를 초과했습니다. 1시간 후 다시 시도하세요.');
  end if;

  -- 만료 시각이 없는 코드는 유효하지 않은 것으로 본다(fail-closed).
  select * into v_user
  from public.app_users
  where access_code = trim(coalesce(p_code, ''))
    and active
    and auth_user_id is null
    and code_expires_at is not null
    and code_expires_at > now()
    and (access_expires_on is null or access_expires_on >= current_date)
  limit 1
  for update;

  if v_user.id is null then
    update public.auth_claim_attempts
    set failed_attempts = least(failed_attempts + 1, 5)
    where auth_user_id = v_auth_user_id;
    return jsonb_build_object(
      'ok', false,
      'error', '연결 코드가 올바르지 않거나 만료됐습니다. 관리자에게 재발급을 요청하세요.'
    );
  end if;

  update public.app_users
  set auth_user_id = v_auth_user_id,
      access_code = 'internal-' || replace(gen_random_uuid()::text, '-', '')
  where id = v_user.id;

  delete from public.auth_claim_attempts where auth_user_id = v_auth_user_id;

  perform public.attendance_audit(
    v_user.id, v_auth_user_id, v_user.name, 'claimAccount', true,
    jsonb_build_object('role', v_user.role, 'permissionLevel', v_user.permission_level)
  );

  return jsonb_build_object('ok', true, 'alreadyLinked', false);
exception
  when unique_violation then
    return jsonb_build_object('ok', false, 'error', '이미 다른 운영자 권한과 연결된 이메일입니다.');
end;
$$;


-- ----------------------------------------------------------------------------
-- 1 & 3 & 4. 최상위 진입점 교체
-- ----------------------------------------------------------------------------
alter function public.attendance_api(jsonb) rename to attendance_api_permission_legacy;
revoke all on function public.attendance_api_permission_legacy(jsonb) from public, anon, authenticated;

create or replace function public.attendance_api(p_request jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_auth_user_id uuid := auth.uid();
  v_action text := trim(coalesce(p_request->>'action', ''));
  v_user public.app_users%rowtype;
  v_current_hash text;
  v_result jsonb;
  v_error text;
  v_detail jsonb;
begin
  if v_auth_user_id is null then
    return jsonb_build_object('ok', false, 'code', 'AUTH_REQUIRED', 'error', '로그인이 필요합니다.');
  end if;

  select * into v_user
  from public.app_users
  where auth_user_id = v_auth_user_id
    and active
    and (access_expires_on is null or access_expires_on >= current_date)
  limit 1;
  if v_user.id is null then
    return jsonb_build_object('ok', false, 'code', 'ACCOUNT_NOT_LINKED', 'error', '운영자 권한을 연결하세요.');
  end if;

  select encrypted_password into v_current_hash
  from auth.users
  where id = v_auth_user_id;

  -- 강제 변경 대상자를 처음 본 순간의 해시를 기준값으로 고정한다.
  -- completePasswordChange 를 첫 요청으로 보내도 이 시점의 값이 기준이 되므로
  -- "바꾸지 않고 플래그만 내리는" 우회가 성립하지 않는다.
  if v_user.must_change_password and v_user.password_baseline is null then
    update public.app_users
    set password_baseline = v_current_hash
    where id = v_user.id;
    v_user.password_baseline := v_current_hash;
  end if;

  if v_action = 'completePasswordChange' then
    if not v_user.must_change_password then
      return jsonb_build_object('ok', true);
    end if;
    if v_current_hash is null or v_current_hash = v_user.password_baseline then
      perform public.attendance_audit(
        v_user.id, v_auth_user_id, v_user.name, v_action, false, '{}'::jsonb
      );
      return jsonb_build_object(
        'ok', false,
        'code', 'PASSWORD_UNCHANGED',
        'error', '비밀번호가 아직 변경되지 않았습니다. 새 비밀번호를 먼저 설정하세요.'
      );
    end if;
    update public.app_users
    set must_change_password = false,
        password_baseline = null,
        updated_at = now()
    where id = v_user.id;
    perform public.attendance_audit(
      v_user.id, v_auth_user_id, v_user.name, v_action, true, '{}'::jsonb
    );
    return jsonb_build_object('ok', true);
  end if;

  v_result := public.attendance_api_permission_legacy(p_request);

  -- 3. 예기치 못한 DB 오류의 원문(sqlerrm)은 서버 로그에만 남기고
  --    클라이언트에는 일반 메시지를 돌려준다.
  v_error := v_result->>'error';
  if v_error like '요청 처리 오류: %' then
    raise log 'attendance_api internal error (user=%, action=%): %', v_user.id, v_action, v_error;
    v_result := v_result || jsonb_build_object(
      'error', '요청을 처리하지 못했습니다. 잠시 후 다시 시도하세요.'
    );
  end if;

  -- 4. 권한·소속을 바꾸는 요청은 성공·실패 모두 기록한다.
  if v_action in (
    'setLeader', 'clearLeader', 'regenerateCode', 'renewMembers', 'assignGroup',
    'createAdminInvitation', 'updateAdmin', 'regenerateAdminCode',
    'deactivateAdmin', 'reactivateAdmin'
  ) then
    v_detail := jsonb_strip_nulls(jsonb_build_object(
      'groupId', p_request->>'groupId',
      'memberId', p_request->>'memberId',
      'targetUserId', coalesce(p_request->>'userId', v_result->>'userId'),
      'permissionLevel', p_request->>'permissionLevel',
      'expiresOn', p_request->>'expiresOn',
      'assignmentCount', case
        when jsonb_typeof(p_request->'assignments') = 'array'
        then to_jsonb(jsonb_array_length(p_request->'assignments'))
      end,
      'moved', v_result->'moved',
      'settled', v_result->'settled',
      'error', case
        when coalesce((v_result->>'ok')::boolean, false) then null
        else v_result->>'error'
      end
    ));
    perform public.attendance_audit(
      v_user.id, v_auth_user_id, v_user.name, v_action,
      coalesce((v_result->>'ok')::boolean, false), v_detail
    );
  end if;

  return v_result;
end;
$$;


